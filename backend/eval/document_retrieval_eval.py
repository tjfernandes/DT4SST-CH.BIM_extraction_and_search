"""HBIM-073 §52 — pure replay and retrieval metrics for the document core.

Pure and offline: no OpenSearch, no embedding service, no reranker, no clock and
no randomness. The caller supplies the per-source rankings (produced live by the
operator harness, or by the ephemeral-OpenSearch integration suite) and this
module recomputes the §12 metric family through the **real** production fusion —
``retrieval.rrf.fuse`` — so the reported numbers describe the ranking production
actually serves.

Under the reviewed mode (`disabled_rrf_only`, §32 Mode C) the served ranking
*is* raw RRF, so `rrf_raw` is the method the §54 quality bars apply to and the
`reranked` method is reported as ``None`` rather than fabricated.

This module writes nothing. Artifacts are produced by dedicated operator
commands and reviewed before they are committed (§57).
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

from retrieval.document_retrieval import DOCUMENT_DECISION_MODE
from retrieval.rrf import CANDIDATES_PER_SOURCE, RRF_K, Candidate, fuse

__all__ = [
    "CORPUS_ID",
    "DocumentGold",
    "METHODS",
    "evaluate_method",
    "fuse_rankings",
    "load_gold",
    "ndcg_at_10",
    "mrr_at_10",
    "recall_at_k",
    "replay",
]

CORPUS_ID = "document-retrieval-gold-v1"
GOLD_DIR = Path(__file__).resolve().parent / "dataset" / "document_retrieval"
#: §52 reports every method separately; nothing is averaged into one score.
METHODS: tuple[str, ...] = ("bm25", "dense", "rrf_raw", "reranked")


@dataclass(frozen=True)
class DocumentGold:
    """The frozen corpus/queries/qrels, keyed by the ``cNN`` gold labels."""

    corpus: dict[str, dict[str, Any]]
    queries: tuple[dict[str, Any], ...]
    qrels: dict[str, dict[str, int]]
    project_id: str
    active_revisions: frozenset[str]
    active_link_revisions: frozenset[str]

    def label_of(self, chunk_id: str) -> str | None:
        for label, record in self.corpus.items():
            if record["chunk_id"] == chunk_id:
                return label
        return None

    def in_scope(self, label: str) -> bool:
        record = self.corpus[label]
        return (
            record["project_id"] == self.project_id
            and record["revision_id"] in self.active_revisions
            and record["link_revision_id"] in self.active_link_revisions
        )


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def load_gold(directory: Path | None = None, *, project_id: str = "proj-ret") -> DocumentGold:
    """Load the committed gold. Never mutated, never regenerated by a test."""
    root = directory or GOLD_DIR
    corpus = {f"c{row['chunk_index']:02d}": row for row in _read_jsonl(root / "corpus.jsonl")}
    queries = tuple(_read_jsonl(root / "queries.jsonl"))
    qrels: dict[str, dict[str, int]] = {row["query_id"]: {} for row in queries}
    for row in _read_jsonl(root / "qrels.jsonl"):
        qrels[row["query_id"]][row["chunk_id"]] = row["grade"]
    # The active map is derived from the corpus itself: the revision carried by
    # the most recent chunk of each document. Superseded rows are excluded
    # because a newer revision of the same document exists.
    latest: dict[str, str] = {}
    latest_links: dict[str, str] = {}
    for record in corpus.values():
        document = record["document_id"]
        latest[document] = max(latest.get(document, ""), record["revision_id"])
        latest_links[document] = max(latest_links.get(document, ""), record["link_revision_id"])
    return DocumentGold(
        corpus=corpus,
        queries=queries,
        qrels=qrels,
        project_id=project_id,
        active_revisions=frozenset(latest.values()),
        active_link_revisions=frozenset(latest_links.values()),
    )


# --------------------------------------------------------------------------- #
# §12 metrics — exact definitions, 6-decimal rounding
# --------------------------------------------------------------------------- #
def recall_at_k(ranking: Sequence[str], relevance: Mapping[str, int], k: int) -> float | None:
    relevant = {label for label, grade in relevance.items() if grade >= 1}
    if not relevant:
        return None
    return round(len(relevant & set(ranking[:k])) / len(relevant), 6)


def ndcg_at_10(ranking: Sequence[str], relevance: Mapping[str, int]) -> float | None:
    if not relevance:
        return None
    gain = sum(
        (2 ** relevance.get(label, 0) - 1) / math.log2(rank + 1)
        for rank, label in enumerate(ranking[:10], start=1)
    )
    ideal_grades = sorted(relevance.values(), reverse=True)[:10]
    ideal = sum(
        (2**grade - 1) / math.log2(rank + 1) for rank, grade in enumerate(ideal_grades, start=1)
    )
    return round(gain / ideal, 6) if ideal else None


def mrr_at_10(ranking: Sequence[str], relevance: Mapping[str, int]) -> float | None:
    if not relevance:
        return None
    for rank, label in enumerate(ranking[:10], start=1):
        if relevance.get(label, 0) >= 1:
            return round(1.0 / rank, 6)
    return 0.0


def _mean(values: Sequence[float]) -> float:
    return round(math.fsum(values) / len(values), 6) if values else 0.0


def fuse_rankings(bm25: Sequence[str], dense: Sequence[str]) -> list[str]:
    """Complete-union RRF through the production primitive, unchanged (§28).

    Synthetic descending scores stand in for the per-source scores: RRF depends
    only on *ranks*, so the fused order is identical to the live one. This is
    what makes the pure replay a faithful description of the served ranking.
    """

    def to_candidates(ids: Sequence[str], source: Any) -> list[Candidate]:
        return [
            Candidate(source_id=identifier, source=source, rank=rank, score=float(-rank))
            for rank, identifier in enumerate(ids[:CANDIDATES_PER_SOURCE], start=1)
        ]

    return [
        row.source_id
        for row in fuse(to_candidates(bm25, "bm25"), to_candidates(dense, "dense"), rrf_k=RRF_K)
    ]


def evaluate_method(
    rankings: Mapping[str, Sequence[str]], gold: DocumentGold
) -> dict[str, Any]:
    """The §12/§52 metric family for one method, reported on its own."""
    graded = [query for query in rankings if gold.qrels.get(query)]
    returned = [label for ranking in rankings.values() for label in ranking]

    in_scope = [label for label in returned if label in gold.corpus and gold.in_scope(label)]
    known = [label for label in returned if label in gold.corpus]
    forbidden = sorted({label for label in known if not gold.in_scope(label)})

    return {
        "queries": len(rankings),
        "graded_queries": len(graded),
        "ndcg_at_10": _mean([ndcg_at_10(rankings[q], gold.qrels[q]) or 0.0 for q in graded]),
        "recall_at_1": _mean([recall_at_k(rankings[q], gold.qrels[q], 1) or 0.0 for q in graded]),
        "recall_at_5": _mean([recall_at_k(rankings[q], gold.qrels[q], 5) or 0.0 for q in graded]),
        "recall_at_10": _mean([recall_at_k(rankings[q], gold.qrels[q], 10) or 0.0 for q in graded]),
        "mrr_at_10": _mean([mrr_at_10(rankings[q], gold.qrels[q]) or 0.0 for q in graded]),
        # §12 — both must be exactly 1.0; a single violation is a gate failure.
        "project_isolation": round(len(in_scope) / len(known), 6) if known else 1.0,
        "active_revision_accuracy": round(len(in_scope) / len(known), 6) if known else 1.0,
        "forbidden_ids": forbidden,
        "forbidden_id_count": len(forbidden),
        # Citation identity: every returned chunk must carry the authored
        # document, page and stable base id.
        "document_accuracy": _citation_accuracy(known, gold, "document_id"),
        "page_accuracy": _citation_accuracy(known, gold, "page_number"),
        "stable_citation_accuracy": _citation_accuracy(known, gold, "base_chunk_id"),
        "zero_relevant_returned": {
            query: list(ranking[:3])
            for query, ranking in sorted(rankings.items())
            if not gold.qrels.get(query)
        },
    }


def _citation_accuracy(labels: Sequence[str], gold: DocumentGold, field: str) -> float:
    if not labels:
        return 1.0
    correct = sum(1 for label in labels if gold.corpus[label].get(field) is not None)
    return round(correct / len(labels), 6)


def replay(
    *,
    bm25: Mapping[str, Sequence[str]],
    dense: Mapping[str, Sequence[str]],
    gold: DocumentGold | None = None,
    reranked: Mapping[str, Sequence[str]] | None = None,
) -> dict[str, Any]:
    """Report every method separately (§52); never a single blended score."""
    resolved = gold or load_gold()
    if sorted(bm25) != sorted(dense):
        raise ValueError("bm25 and dense rankings must cover the same query set")
    rrf_raw = {query: fuse_rankings(bm25[query], dense[query]) for query in bm25}

    report: dict[str, Any] = {
        "corpus_id": CORPUS_ID,
        "decision_mode": DOCUMENT_DECISION_MODE,
        "rrf_k": RRF_K,
        "candidates_per_source": CANDIDATES_PER_SOURCE,
        "served_method": "rrf_raw",
        "methods": {
            "bm25": evaluate_method(bm25, resolved),
            "dense": evaluate_method(dense, resolved),
            "rrf_raw": evaluate_method(rrf_raw, resolved),
            # Mode C never calls the reranker, so there is nothing to report
            # here. Emitting fabricated numbers would misdescribe the path.
            "reranked": None if reranked is None else evaluate_method(reranked, resolved),
        },
        "union_membership": {
            query: sorted(set(bm25[query]) | set(dense[query])) == sorted(set(rrf_raw[query]))
            for query in sorted(bm25)
        },
    }
    return report
