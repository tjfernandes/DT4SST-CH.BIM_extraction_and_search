def _validate(pack, claims) -> AbstentionReason | None:
    """Oracle covering both parse-time and validate-time rejection."""
    try:
        draft = parse_draft(json.dumps({"status": "answer", "claims": claims}))
        validate_draft(draft, build_reference_map(pack))
    except DraftRejection as rejection:
        return rejection.reason
    return None


